#pragma once
//==========================================================//
// 【GameRecord.h】シーンをまたいで残す記録(今のステージ、各ステージのタイム)
//==========================================================//
// Game が1つ持ち、ポインタでシーンに渡す。
//
#define STAGE_COUNT (6) // ステージの数

struct GameRecord
{
	int stageNo;					// 今のステージ(0〜STAGE_COUNT-1)
	float clearTime[STAGE_COUNT];	// 各ステージのクリアタイム(秒)
};
