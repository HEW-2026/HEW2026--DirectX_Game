void Stage::Init()
{
	// タイル画像を読み込む(横3分割、縦4分割)
	m_tile.Init("asset/Test_Tile.png", 3, 4);
	m_tile.SetSize(TILE_SIZE * PIXEL_SCALE, TILE_SIZE * PIXEL_SCALE, 0.0f);

	// 仮に全マスを草地の上端(B)で表示する
	m_tile.numU = 1;
	m_tile.numV = 0;

	// テスト用マップをコピーする
	for (int y = 0; y < STAGE_H; y++) {
		for (int x = 0; x < STAGE_W; x++) {
			m_data[y][x] = g_testMap[y][x];
		}
	}
}

void Stage::Draw()
{
	for (int y = 0; y < STAGE_H; y++) {
		for (int x = 0; x < STAGE_W; x++) {
			// 空気のマスは描画しない
			if (m_data[y][x] == 0) continue;

			// マスの中心の座標(ドット、左上が原点、下が+)
			int dotX = x * TILE_SIZE + TILE_SIZE / 2;
			int dotY = y * TILE_SIZE + TILE_SIZE / 2;

			// 画面の座標に変換する(画面中央が原点、上が+)
			float screenX = (float)((dotX - VIEW_WIDTH / 2) * PIXEL_SCALE);
			float screenY = (float)((VIEW_HEIGHT / 2 - dotY) * PIXEL_SCALE);

			m_tile.SetPos(screenX, screenY, 0.0f);
			m_tile.Draw();
		}
	}
}

void Stage::Uninit()
{
	m_tile.Uninit(); // タイルを終了
}