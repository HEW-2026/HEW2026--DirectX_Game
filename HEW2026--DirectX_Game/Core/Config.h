#pragma once
//==========================================================//
// 【Config.h】ゲーム全体で使う設定値
//==========================================================//
//
// 単位と座標(ゲーム全体で共通)
//   ドット      ：ゲームの長さの単位。ゲーム画面は 960×540 ドット
//   ピクセル    ：実際の画面の点。画面は 1920×1080 ピクセル。1ドット = PIXEL_SCALE ピクセル
//   ワールド座標：ステージの中の位置(ドット)。ステージの左下が原点、右が+x、上が+y
//   画面座標    ：Object に渡す位置(ピクセル)。画面の中央が原点、右が+x、上が+y
//   角度        ：全部「度」。0度で右、90度で上(反時計回り)
//   速さ        ：仕様書は「秒」で書いてあるので、PER_SEC() で1フレームあたりに直して使う
//
// 仕様書(v60)・HTMLのプロトタイプから値を写す時の注意
//   ・長さは SPEC_PX() でドットに直す
//   ・プロトタイプは「下が+y」なので、yの符号と角度の向き(時計回り)を逆にする
//

#define FPS				(60)				// 1秒あたりのフレーム数
#define PER_SEC(v)		((v)/(float)FPS)	// 秒単位の値を1フレームあたりに変換する

#define VIEW_WIDTH		(960)				// ゲーム画面の横幅(ドット)
#define VIEW_HEIGHT		(540)				// ゲーム画面の縦幅(ドット)
#define PIXEL_SCALE		(2)					// 1ドットを何ピクセルで描くか
#define TILE_SIZE		(32)				// タイル1マスの大きさ(ドット)

// 仕様書(v60)の px をドットに変換する(仕様書は画面の縦 720px が基準)
// 例：仕様書の「魚の半径 16px」→ SPEC_PX(16.0f) = 12ドット
#define SPEC_PX(v)		((v) * VIEW_HEIGHT / 720.0f)

#define PI				(3.14159f)			// 円周率
#define DEG_TO_RAD		(PI / 180.0f)		// 度 → ラジアン(sinf・cosf に渡す前に掛ける)
#define RAD_TO_DEG		(180.0f / PI)		// ラジアン → 度(atan2f の結果に掛ける)

#define HITSTOP_SCALE	(0.1f)				// ヒットストップ中の時間の進み(倍)
#define DEBUG_DRAW		(1)					// デバッグ表示(0:無効、1:有効。F1で切り替え)。提出時は0にする
